"""Generate Phase 6 reference documents from the manifest, model spec and QA results (no hand-copied numbers).

Usage:  .venv\\Scripts\\python.exe -m intelligent_demand.bi.docs
"""

import json
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
DOCS = ROOT / "docs"


def load():
    manifest = json.loads((ROOT / "reports/powerbi/data_manifest.json").read_text(encoding="utf-8"))
    spec = yaml.safe_load((ROOT / "configs/powerbi_model.yaml").read_text(encoding="utf-8"))
    qa = json.loads((ROOT / "reports/powerbi/qa_results.json").read_text(encoding="utf-8"))
    return manifest, spec, qa


def data_dictionary(manifest, spec):
    lines = [
        "# Phase 6 data dictionary and lineage",
        "",
        "Generated by `python -m intelligent_demand.bi.export` and `python -m intelligent_demand.bi.docs`.",
        "Every table is a compact CSV in `artifacts/powerbi/data/` (git-ignored, reproducible). Row counts and",
        "SHA-256 values come from `reports/powerbi/data_manifest.json`. No final-holdout target was read.",
        "",
        "## Lineage",
        "",
        "Saved Phase 3-5 evidence -> `bi/export.py` (read-only, hash-checked adapters) -> reporting CSVs ->",
        "Power Query `LoadReportingTable` (explicit types, early projection, empty text kept as null) ->",
        "TMDL star schema -> DAX measures in `_Measures` -> PBIR report pages.",
        "",
        "Source fingerprints:",
        "",
    ]
    for name, source in manifest["sources"].items():
        lines.append(f"- `{name}`: `{source['path']}` sha256 `{source['sha256'][:16]}...`")
    lines += ["", "## Tables", "", "| Table | Grain | Business key | Rows |", "|---|---|---|---:|"]
    for name, entry in manifest["tables"].items():
        lines.append(
            f"| {name} | {entry['grain']} | {', '.join(entry['keys'])} | {entry['rows']:,} |"
        )
    lines += [
        "",
        "## Relationships",
        "",
        "All are many-to-one, single direction, active. Dimensions never filter each other, so there are",
        "no ambiguous paths; demand pattern and dataset are denormalised onto DimSeries as attributes only.",
        "",
        "```mermaid",
        "erDiagram",
    ]
    for fact, column, dim, _ in spec["relationships"]:
        lines.append(f'    {dim} ||--o{{ {fact} : "{column}"')
    lines += ["```", "", "## Columns", ""]
    for name, entry in manifest["tables"].items():
        meta = spec["tables"][name]
        rename = meta.get("rename", {})
        visibility = (
            "all hidden (use measures)"
            if meta.get("hide_all")
            else f"hidden: {', '.join(meta.get('hidden', [])) or 'none'}"
        )
        lines += [
            f"### {name}",
            "",
            meta["description"],
            "",
            f"Columns ({visibility}): "
            + ", ".join(f"`{rename.get(c, c)}`" for c in entry["columns"]),
            "",
        ]
    return "\n".join(lines)


def measure_catalogue(spec):
    folders = defaultdict(list)
    for measure in spec["measures"]:
        folders[measure["folder"].split("\\")[0]].append(measure)
    lines = [
        "# Phase 6 DAX measure catalogue",
        "",
        f"{len(spec['measures'])} measures in the `_Measures` table, generated from `configs/powerbi_model.yaml`.",
        "Pooled metrics use additive numerators and denominators; ratios are never averaged. Macro MASE/RMSSE",
        "follow the Phase 4 definition (mean over origins of the per-origin series mean, undefined scales",
        "excluded). Scope guards return BLANK when datasets, model roles, scenarios or policies would be mixed.",
        "All inventory values are hypothetical normalised cost units (NCU), never savings.",
        "",
    ]
    for folder, measures in folders.items():
        lines += [f"## {folder}", ""]
        for measure in measures:
            lines += [
                f"### {measure['name']}",
                "",
                measure["description"],
                "",
                f"Folder `{measure['folder']}`; format `{measure.get('format', 'text')}`"
                + ("; hidden" if measure.get("hidden") else ""),
                "",
                "```dax",
                measure["expression"].strip(),
                "```",
                "",
            ]
    return "\n".join(lines)


def qa_document(qa):
    summary = qa["summary"]
    lines = [
        "# Phase 6 dashboard QA results",
        "",
        "Generated from `reports/powerbi/qa_results.json` (`python -m intelligent_demand.bi.qa`). PASS/FAIL",
        "comes from the deterministic rules in `configs/powerbi_qa.yaml`, not from interpretation.",
        "",
        f"Overall: **{summary['overall']}**. Rules {summary['rules']}: {summary['pass']} pass, "
        f"{summary['warning']} warning, {summary['fail']} fail, {summary['error']} error.",
        "",
        "Layers: A source evidence, B reporting data, C semantic model (live engine), D DAX business logic",
        "(live engine vs saved scientific evidence), E report definition.",
        "",
        "| Rule | Layer | Severity | Status | Description | Actual | Tolerance |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in qa["results"]:
        actual = str(r["actual"]).replace("|", "/")[:140]
        tolerance = json.dumps(r["tolerance"]) if r.get("tolerance") else ""
        lines.append(
            f"| {r['id']} | {r['layer']} | {r['severity']} | {r['status']} | {r['description']} | "
            f"{actual} | {tolerance} |"
        )
    return "\n".join(lines) + "\n"


def build():
    manifest, spec, qa = load()
    for name, text in (
        ("PHASE6_DATA_DICTIONARY.md", data_dictionary(manifest, spec)),
        ("PHASE6_DAX_MEASURE_CATALOGUE.md", measure_catalogue(spec)),
        ("PHASE6_QA_RESULTS.md", qa_document(qa)),
    ):
        (DOCS / name).write_text(text.rstrip() + "\n", encoding="utf-8")
        print("written", name)


if __name__ == "__main__":
    build()
